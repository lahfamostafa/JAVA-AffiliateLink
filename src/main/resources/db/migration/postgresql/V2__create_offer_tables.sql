-- ==========================================
-- 1. TABLE OFFERS
-- ==========================================

CREATE TABLE offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    landing_url VARCHAR(2048) NOT NULL,
    niche VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ==========================================
-- 2. TABLE TAGS
-- ==========================================

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT chk_tag_name_lowercase
        CHECK (name = LOWER(name))
);


-- ==========================================
-- 3. TABLE DE LIAISON OFFERS / TAGS
-- ==========================================

CREATE TABLE offer_tags (
    offer_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,

    PRIMARY KEY (offer_id, tag_id),

    CONSTRAINT fk_offer_tags_offer
        FOREIGN KEY (offer_id)
        REFERENCES offers(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_offer_tags_tag
        FOREIGN KEY (tag_id)
        REFERENCES tags(id)
        ON DELETE CASCADE
);


-- ==========================================
-- 4. TABLE CAMPAIGNS
-- ==========================================

CREATE TABLE campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    budget NUMERIC(12, 2) NOT NULL,
    payout_model VARCHAR(20) NOT NULL,
    payout_value NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    CONSTRAINT fk_campaign_offer
        FOREIGN KEY (offer_id)
        REFERENCES offers(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_campaign_budget
        CHECK (budget > 0),

    CONSTRAINT chk_campaign_dates
        CHECK (end_date > start_date),

    CONSTRAINT chk_campaign_payout_model
        CHECK (
            payout_model IN ('CPC', 'CPL', 'CPA_FIXED', 'CPA_PERCENT')
        ),

    CONSTRAINT chk_campaign_payout_value
        CHECK (
            (payout_model IN ('CPC', 'CPL', 'CPA_FIXED')
                AND payout_value > 0)
            OR
            (payout_model = 'CPA_PERCENT'
                AND payout_value > 0
                AND payout_value <= 100)
        ),

    CONSTRAINT chk_campaign_status
        CHECK (status IN ('DRAFT', 'ACTIVE', 'PAUSED', 'ENDED'))
);


-- ==========================================
-- 5. INDEXES
-- ==========================================

CREATE INDEX idx_offers_advertiser_id
    ON offers(advertiser_id);

CREATE INDEX idx_offers_niche
    ON offers(niche);

CREATE INDEX idx_campaigns_offer_id
    ON campaigns(offer_id);

CREATE INDEX idx_campaigns_status
    ON campaigns(status);